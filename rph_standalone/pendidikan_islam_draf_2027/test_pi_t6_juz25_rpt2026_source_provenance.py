"""Old 2026 RPT impossible Shura range is a corrected legacy source bug."""
import unittest
from pi_t6_juz25_rpt2026_source_provenance import audit,LEGACY


class PIY6Juz25LegacySourceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.r=audit()

    def test_original_2026_unsafe_range_and_2027_repair(self):
        r=self.r
        self.assertEqual(len(LEGACY),7)
        self.assertEqual(r["source_2026_table_rows_checked"],
                         [[0,3],[1,2],[2,2],[3,2],[4,2],[5,2],[6,2]])
        self.assertEqual(r["legacy_source_shura_pdp6_ayat"],[33,77])
        self.assertEqual(r["quran_shura_last_ayah"],53)
        self.assertEqual(r["legacy_out_of_bounds_shura_ayah_count"],24)
        self.assertEqual(r["legacy_duplicated_shura_ayat_count"],2)
        self.assertEqual(r["newer_2027_shura_pdp6_ayat"],[33,51])
        self.assertIs(r["newer_2027_corrected_legacy_out_of_bounds"],True)
        self.assertIs(r["newer_2027_corrected_legacy_shura_overlap"],True)

    def test_source_omissions_still_unresolved(self):
        r=self.r
        self.assertEqual(r["legacy_inherited_juz25_valid_unique_ayat"],179)
        self.assertEqual(r["legacy_inherited_juz25_missing_ayat"],67)
        self.assertEqual(r["newer_2027_juz25_missing_ayat"],67)
        self.assertEqual(r["inherited_four_unmapped_blocks"],
                         [[41,47,54],[43,74,89],[44,1,39],[45,34,37]])
        self.assertIs(r["live_rpt_revised"],False)
        self.assertIs(r["held_l006_autogenerated"],False)
        self.assertIs(r["content_expert_approved"],False)
        self.assertEqual(r["release"],"NO_GO")

if __name__=="__main__":
    unittest.main()
