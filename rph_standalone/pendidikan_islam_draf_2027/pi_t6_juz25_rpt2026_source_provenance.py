"""Original 2026 Year6 RPT is the source of four inherited Juz25 gaps.

The 2026 user Drive Word source was visually / table-text checked:
Rozayus_RPT_Pendidikan_Islam_Tahun_6_SK_2026.docx
SHA-256 6b0cb9ac986be8cc0350b66db341e2fefc9a698b0c78be0406020149107b1b14

The old 2026 table assigns ash-Shura 42:33-77 (surah has only 53
ayat), then repeats 42:52-53 in the next row. Original 2026 also
omits the SAME four Juz25 segments as the corrected 2027 RPT:
Fussilat 47-54, Zukhruf 74-89, Dukhan 1-39, Jathiyah 34-37.

The 2027 catalog already corrects the bad Shura row to 42:33-51.
This does not repair the 67 omission. This CI checker preserves
historical source evidence and explicitly forbids automatic RPT rewrites.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
from pi_quality_audit import ROOT
from pi_t6_juz25_sequence_gap_audit import audit as juz25_2027,JUZ25

SOURCE2026_ID="1WJTT7wm3aiN4F7YHMf1v_Qj6tuWu597a"
SOURCE2026_SHA="6b0cb9ac986be8cc0350b66db341e2fefc9a698b0c78be0406020149107b1b14"
SOURCE2027_ID="1T380Ot_gG58JhxanELMM0z-gr6wmSJcL"
SOURCE2027_SHA="b39a07b2dd7ef6062912f12fd43e63f87a98b13bde3885c925e88a37dac70e5b"
# Original 2026 Word table 0 row3 through table6 row2; mapped to the
# corresponding (not native 2026) 2027 PdP labels by sequence.
LEGACY={
    "T6-L002":((42,1,32),),
    "T6-L006":((42,33,77),),  # impossible 42:54-77 (24 ayat)
    "T6-L010":((42,52,53),(43,1,33)),  # 2 ayat repeat
    "T6-L014":((43,34,73),),
    "T6-L018":((44,40,59),),
    "T6-L022":((45,1,22),),
    "T6-L026":((45,23,33),(46,1,14)),  # 46 = Juz26
}


def audit(root=ROOT):
    newer=juz25_2027(root)
    cat=json.loads((Path(root)/"year6.json").read_text(encoding="utf-8"))
    assert cat["year"]==6 and len(cat["records"])==143
    assert len(LEGACY)==7
    seen=set()
    invalid=[]
    duplicate=[]
    for id_,spans in LEGACY.items():
        row=cat["records"][int(id_[-3:])-1]
        assert row["id"]==id_ and row["verified_ready"] is False
        for surah,low,high in spans:
            if surah==46:
                assert id_=="T6-L026" and (surah,low,high)==(46,1,14)
                continue
            assert surah in JUZ25
            lo,hi=JUZ25[surah]
            for ayah in range(low,high+1):
                token=(surah,ayah)
                if ayah<lo or ayah>hi:
                    invalid.append(token)
                elif token in seen:
                    duplicate.append(token)
                else:
                    seen.add(token)
    expected={(s,v) for s,(first,last) in JUZ25.items()
              for v in range(first,last+1)}
    missing=expected-seen
    assert len(seen)==179
    assert len(invalid)==24 and invalid==[(42,i) for i in range(54,78)]
    assert duplicate==[(42,52),(42,53)]
    assert len(missing)==67
    assert len(newer["rows"])==4 and newer["juz25_ayah_missing_in_rpt"]==67
    assert (42,52) in seen and (42,53) in seen
    assert cat["records"][5]["withheld"] is True
    assert cat["records"][5]["id"]=="T6-L006" and "fields" not in cat["records"][5]
    assert cat["records"][9]["fields"]["sp"].find("52-53")!=-1
    return {
        "purpose":"Original 2026 Juz25 RPT root-cause comparison, no RPT or catalog rewrite",
        "source_2026_docx_drive_id":SOURCE2026_ID,
        "source_2026_docx_sha256":SOURCE2026_SHA,
        "source_2027_pdf_drive_id":SOURCE2027_ID,
        "source_2027_pdf_sha256":SOURCE2027_SHA,
        "source_2026_table_rows_checked":[[0,3],[1,2],[2,2],[3,2],[4,2],[5,2],[6,2]],
        "legacy_source_shura_pdp6_ayat":[33,77],
        "quran_shura_last_ayah":53,
        "legacy_out_of_bounds_shura_ayah_count":24,
        "legacy_duplicated_shura_ayat_count":2,
        "legacy_inherited_juz25_valid_unique_ayat":179,
        "legacy_inherited_juz25_missing_ayat":67,
        "newer_2027_shura_pdp6_ayat":[33,51],
        "newer_2027_corrected_legacy_out_of_bounds":True,
        "newer_2027_corrected_legacy_shura_overlap":True,
        "newer_2027_juz25_missing_ayat":67,
        "inherited_four_unmapped_blocks":[[41,47,54],[43,74,89],[44,1,39],[45,34,37]],
        "live_rpt_revised":False,
        "held_l006_autogenerated":False,
        "content_expert_approved":False,
        "release":"NO_GO"
    }


def write(path,root=ROOT):
    result=audit(root)
    Path(path).write_text(json.dumps(result,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(result,ensure_ascii=False,indent=2))


