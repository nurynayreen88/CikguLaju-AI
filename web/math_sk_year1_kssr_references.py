def _with_references(row):
    entry = _REFERENCES.get(row.get("pdp_sequence_code"))
    if not entry:
        return row
    sp, title, volume, textbook, activitybook = entry
    if (row.get("sp_code"), row.get("sk_code"), row.get("unit_code")) != (
            sp, sp.rsplit(".", 1)[0], f"{sp.split('.')[0]}.0"):
        return row

    updated = dict(row)
    if row.get("pdp_title") == f"{row.get('unit_title')} — {sp}":
        updated["pdp_title"] = title
    if not row.get("textbook_ref"):
        updated["textbook_ref"] = f"Buku Teks Jilid {volume}, hlm. {textbook}"
    if not row.get("activitybook_ref"):
        updated["activitybook_ref"] = f"Buku Aktiviti Jilid {volume}, hlm. {activitybook}"
    return updated


def install(runtime):
    read_rows = getattr(runtime, "_sm2542_rows", None)
    if not callable(read_rows):
        return

    def read_with_references(year_label, subject):
        rows = read_rows(year_label, subject)
        if (year_label, subject) == ("Tahun 1", "Matematik"):
            return [_with_references(row) for row in rows]
        return rows

    runtime._sm2542_rows = read_with_references
