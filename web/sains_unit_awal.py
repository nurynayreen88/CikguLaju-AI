LESSON_BY_CODE = {lesson.code: lesson for lesson in LESSONS}


def add_opening_units(year, rows):
    if not rows or year not in STANDARDS:
        return rows
    existing_sk = {
        str(row.get("sk_code") or "").strip()
        for row in rows if row.get("pdp_sequence_code") and row.get("sp_code")
    }
    existing_codes = {str(row.get("pdp_sequence_code") or "").strip() for row in rows}
    return rows + [
        {
            "unit_code": lesson.sk,
            "unit_title": lesson.unit,
            "pdp_sequence_code": lesson.code,
            "source_sequence_no": lesson.number,
            "pdp_title": lesson.title,
            "theme": "Inkuiri dalam Sains",
            "sk_code": lesson.sk,
            "sk_text": SK[lesson.sk],
            "sp_code": standard,
            "sp_text": STANDARDS[year][standard],
            "textbook_ref": f"Buku Teks m/s {lesson.pages}",
            "_sains_opening_lesson": True,
        }
        for lesson in LESSONS
        if lesson.year == year and lesson.sk not in existing_sk and lesson.code not in existing_codes
        for standard in lesson.standards
    ]


def lesson_text(code):
    plan = LESSON_BY_CODE[code]
    return plan_text(plan, STANDARDS[plan.year])


def install(runtime):
    previous = getattr(runtime, "_rph_rows", None)
    if not callable(previous):
        return False

    def rows(state, *args, **kwargs):
        result = previous(state, *args, **kwargs)
        if not state.get("_sains_opening_lesson"):
            return result
        plan = LESSON_BY_CODE[state["pdp_sequence_code"]]
        return plan_rows(result, plan, STANDARDS[plan.year])

    runtime._rph_rows = rows
    return True
