"""RBT 2027 staging curriculum adapter: exact read-only menu/source, fail-closed.

This module is NOT registered into the public Telegram/Web endpoints. It allows
the same curriculum selections to be inspected by either future client without
duplicating RPH content, but does not grant access or create user downloads.
"""
from __future__ import annotations

from copy import deepcopy
from hashlib import sha256
from pathlib import Path
import json

ROOT=Path(__file__).resolve().parents[1]
LEDGER="audits/rbt_t4_t6_manual_release_approval_manifest_20261106.json"
YEARS=(4,5,6)


class RBTSourceUnavailable(RuntimeError):
    pass


def _load(year, *, root=ROOT):
    if type(year) is not int or year not in YEARS:
        raise RBTSourceUnavailable("Tahun RBT tidak disokong")
    path=Path(root)/f"rph_standalone/rbt/tahun_{year}/RPH_RBT_T{year}_2027_DRAF.json"
    if path.is_symlink() or not path.is_file() or path.stat().st_size>800_000:
        raise RBTSourceUnavailable("Sumber RBT utama tidak tersedia")
    try:
        obj=json.loads(path.read_text(encoding="utf-8"))
    except (UnicodeError,ValueError,OSError) as exc:
        raise RBTSourceUnavailable("Sumber RBT tidak sah") from exc
    rows=obj.get("pelajaran")
    if obj.get("tahun")!=year or obj.get("status")!="DRAF_STAGING" or not isinstance(rows,list) or len(rows)!=32:
        raise RBTSourceUnavailable("Sumber RBT belum disahkan untuk diedarkan")
    return obj


def _lookup(year,pdp,*,root=ROOT):
    if type(pdp) is not int or not 1<=pdp<=32:
        raise RBTSourceUnavailable("PdP RBT tidak sah")
    obj=_load(year,root=root)
    row=obj["pelajaran"][pdp-1]
    if row.get("pdp")!=pdp or row.get("tahun")!=year or row.get("review",{}).get("release_ready") is not False:
        raise RBTSourceUnavailable("Status sumber RBT tidak selamat")
    return row


def menu_units(year,*,root=ROOT):
    """Exact Unit N label for successive dropdown, from immutable source file."""
    obj=_load(year,root=root)
    modules=obj["modul"]
    return tuple((m["unit"],f"Unit {m['unit']}: {m['tajuk']}") for m in modules)


def menu_pdp(year,unit,*,root=ROOT):
    """All numbered PdP in one Unit. No autogenerated theme or weeks."""
    if type(unit) is not int:
        raise RBTSourceUnavailable("Unit tidak sah")
    obj=_load(year,root=root)
    matches=obj["pelajaran"]
    if not any(m["unit"]==unit for m in obj["modul"]):
        raise RBTSourceUnavailable("Unit RBT tiada")
    return tuple((r["pdp"],r["tajuk"]) for r in matches if r["unit"]==unit)


def internal_review(year,pdp,*,root=ROOT):
    """Internal QA only. Public route MUST NOT return this as downloadable material."""
    return deepcopy(_lookup(year,pdp,root=root))


def source_fingerprint(year,pdp,*,root=ROOT):
    """Digest binds exact PdP content to that PdP's independent review record."""
    row=_lookup(year,pdp,root=root)
    path=Path(root)/LEDGER
    if path.is_symlink() or not path.is_file() or path.stat().st_size>500_000:
        raise RBTSourceUnavailable("Pagar kelulusan RBT tiada")
    try:
        ledger=json.loads(path.read_text(encoding="utf-8"))
    except (OSError,ValueError,UnicodeError) as exc:
        raise RBTSourceUnavailable("Pagar kelulusan RBT tidak sah") from exc
    rec=[r for r in ledger.get("individual_review",[]) if r.get("id")==row["id"]]
    if len(rec)!=1:
        raise RBTSourceUnavailable("Rekod kelulusan individu tidak konsisten")
    blob=json.dumps({"year":year,"pdp":pdp,"lesson":row,"approval":rec[0]},
                    ensure_ascii=False,sort_keys=True,separators=(",",":"))
    return sha256(blob.encode("utf-8")).hexdigest()


def approved_download_payload(year,pdp,format,*,root=ROOT):
    """Fail-closed pending source, visual, teacher, native and Telegram/Web QA.

    Neither the success of document-preview CI nor a source digest constitutes
    approval. We intentionally do not enable public generation in this branch.
    """
    if format not in ("word","pdf"):
        raise RBTSourceUnavailable("Format tidak disokong")
    _lookup(year,pdp,root=root)
    source_fingerprint(year,pdp,root=root)
    raise RBTSourceUnavailable(
        "RBT belum dibuka: pengesahan aktiviti buku teks, kelulusan individu, "
        "penjana natif dan kesetaraan Telegram/Web belum lengkap."
    )
