"""Member-only referral button in the existing Telegram main menu.

This adapter is installed after all WSGI menu bridges. It preserves the exact
menu generated by CikguLaju and inserts one inline button for an enabled
referrer provisioned in Supabase.
"""
import requests


_BUTTON = {"text": "🎁 Affiliate Saya", "callback_data": "private_referral_home"}


def install(runtime):
    member_lookup = getattr(runtime, "_private_referral_member", None)
    if not callable(member_lookup):
        return False

    original_menu = runtime.menu

    def menu(cid, show_persistent=False):
        # Never block the original menu or change its subscription/credit gates.
        response = original_menu(cid, show_persistent=show_persistent)
        try:
            member = member_lookup(cid)
            if not member or member.get("enabled") is not True:
                return response
        except Exception as exc:
            print("PRIVATE REFERRAL menu lookup unavailable:", type(exc).__name__, flush=True)
            return response

        try:
            payload = response.json() if response is not None else {}
            result = payload.get("result") or {}
            message_id = result.get("message_id")
            rows = (result.get("reply_markup") or {}).get("inline_keyboard") or []
            if not message_id or not rows:
                raise ValueError("menu reply keyboard is unavailable")
            if any(button.get("callback_data") == _BUTTON["callback_data"]
                   for row in rows for button in row):
                return response

            # Keep every existing button and its order. Place near the profile.
            keyboard = [list(row) for row in rows]
            insert_at = next(
                (i + 1 for i, row in enumerate(keyboard)
                 if any(button.get("callback_data") == "account" for button in row)),
                len(keyboard)
            )
            keyboard.insert(insert_at, [dict(_BUTTON)])
            updated = requests.post(
                str(runtime.API) + "/editMessageReplyMarkup",
                json={
                    "chat_id": cid,
                    "message_id": message_id,
                    "reply_markup": {"inline_keyboard": keyboard}
                },
                timeout=12
            )
            if not updated.ok or (updated.json() or {}).get("ok") is not True:
                raise RuntimeError("Telegram did not accept referral button")
        except Exception as exc:
            # Fallback stays private and cannot erase any existing menu buttons.
            print("PRIVATE REFERRAL menu button fallback:", type(exc).__name__, flush=True)
            try:
                runtime.send(cid, "🎁 <b>Referral Saya</b>",
                             [[dict(_BUTTON)]])
            except Exception:
                pass
        return response

    runtime.menu = menu
    return True
