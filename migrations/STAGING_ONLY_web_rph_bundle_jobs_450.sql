-- Never execute against production or expose a browser-side service role.
-- Depends on migration web_google_rph_delivery_quota_448.
BEGIN;

INSERT INTO storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
SELECT 'web-rph-bundles-staging','web-rph-bundles-staging',false,15728640,
 ARRAY['application/pdf','application/vnd.openxmlformats-officedocument.wordprocessingml.document']::text[]
WHERE NOT EXISTS (SELECT 1 FROM storage.buckets
 WHERE id='web-rph-bundles-staging');

DO $verify$
BEGIN
 IF NOT EXISTS (
  SELECT 1 FROM storage.buckets WHERE id='web-rph-bundles-staging'
    AND public = false AND file_size_limit BETWEEN 15728640 AND 20000000
 ) THEN
  RAISE EXCEPTION 'Private RPH bucket must remain private';
 END IF;
END
$verify$;

CREATE TABLE IF NOT EXISTS public.web_rph_bundle_jobs (
 id uuid PRIMARY KEY,
 account_id uuid NOT NULL REFERENCES public.web_accounts(id) ON DELETE RESTRICT,
 selection_sha256 text NOT NULL CHECK (selection_sha256 ~ '^[0-9a-f]{64}$'),
 status text NOT NULL DEFAULT 'prepared'
     CHECK(status IN ('prepared','ready')),
 document_manifest_sha256 text CHECK (
   document_manifest_sha256 IS NULL
   OR document_manifest_sha256 ~ '^[0-9a-f]{64}$'
 ),
 access_mode text CHECK (access_mode IN ('trial','paid')),
 remaining_after integer CHECK (remaining_after BETWEEN 0 AND 10),
 created_at timestamptz NOT NULL DEFAULT now(),
 ready_at timestamptz,
 CONSTRAINT ready_has_manifest CHECK (
    (status='prepared' AND document_manifest_sha256 IS NULL
      AND access_mode IS NULL AND remaining_after IS NULL AND ready_at IS NULL)
    OR
    (status='ready' AND document_manifest_sha256 IS NOT NULL
      AND access_mode IS NOT NULL AND remaining_after IS NOT NULL
      AND ready_at IS NOT NULL)
 )
);

CREATE INDEX IF NOT EXISTS web_rph_bundle_jobs_account
 ON public.web_rph_bundle_jobs(account_id,created_at DESC);
ALTER TABLE public.web_rph_bundle_jobs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.web_rph_bundle_jobs FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE ON public.web_rph_bundle_jobs TO service_role;

-- Server must sign in Google user and derive account_id from signed session.
-- p_job_id is generated by server, persisted once and reused for retry.
-- Browser must never select the job's account or a privileged job id.
CREATE OR REPLACE FUNCTION public.prepare_web_rph_bundle_staging(
 p_account_id uuid,p_job_id uuid,p_selection_sha256 text
) RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER
SET search_path=public,pg_temp AS $body$
DECLARE v_job public.web_rph_bundle_jobs%ROWTYPE;
BEGIN
 IF p_account_id IS NULL OR p_job_id IS NULL OR
     p_selection_sha256 IS NULL OR p_selection_sha256 !~ '^[0-9a-f]{64}$'
 THEN RAISE EXCEPTION 'Invalid private RPH preparation'; END IF;
 INSERT INTO public.web_rph_bundle_jobs(id,account_id,selection_sha256)
 VALUES(p_job_id,p_account_id,p_selection_sha256)
 ON CONFLICT(id) DO NOTHING;
 SELECT * INTO v_job FROM public.web_rph_bundle_jobs WHERE id=p_job_id;
 IF NOT FOUND OR v_job.account_id <> p_account_id
      OR v_job.selection_sha256 <> p_selection_sha256
 THEN RAISE EXCEPTION 'RPH request identity collision'; END IF;
 RETURN jsonb_build_object('job_id',v_job.id,'status',v_job.status);
END;
$body$;

-- Atomic finalize: both files must be present in PRIVATE Storage BEFORE
-- calling the exactly-once credit RPC. Failure/zero balance leaves job
-- prepared (no ready download and no debit).
CREATE OR REPLACE FUNCTION public.complete_web_rph_bundle_staging(
 p_account_id uuid,p_job_id uuid,p_manifest_sha256 text
) RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER
SET search_path=public,storage,pg_temp AS $body$
DECLARE
 v_job public.web_rph_bundle_jobs%ROWTYPE;
 v_result jsonb;
 v_word text;
 v_pdf text;
BEGIN
 IF p_account_id IS NULL OR p_job_id IS NULL OR p_manifest_sha256 IS NULL
      OR p_manifest_sha256 !~ '^[0-9a-f]{64}$'
 THEN RAISE EXCEPTION 'Invalid private RPH completion'; END IF;

 SELECT * INTO v_job FROM public.web_rph_bundle_jobs
  WHERE id=p_job_id AND account_id=p_account_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'RPH job not found for verified account'; END IF;
 IF v_job.status='ready' THEN
   IF v_job.document_manifest_sha256 <> p_manifest_sha256
   THEN RAISE EXCEPTION 'RPH job manifest mismatch'; END IF;
   RETURN jsonb_build_object('allowed',true,'replayed',true,
      'access_mode',v_job.access_mode,'remaining',v_job.remaining_after,
      'job_id',v_job.id,'status','ready');
 END IF;

 v_word := p_account_id::text || '/' || p_job_id::text || '.docx';
 v_pdf := p_account_id::text || '/' || p_job_id::text || '.pdf';
 IF NOT EXISTS (
      SELECT 1 FROM storage.objects
      WHERE bucket_id='web-rph-bundles-staging' AND name=v_word)
  OR NOT EXISTS (
      SELECT 1 FROM storage.objects
      WHERE bucket_id='web-rph-bundles-staging' AND name=v_pdf)
 THEN RAISE EXCEPTION 'Both private native RPH files must exist'; END IF;

 -- Legacy Telegram credit data is not involved in this staging UUID ledger.
 v_result := public.consume_web_rph_bundle_staging(
      p_account_id,p_job_id,p_manifest_sha256);
 IF (v_result->>'allowed')::boolean IS DISTINCT FROM true THEN
   RETURN v_result || jsonb_build_object('job_id',p_job_id,'status','prepared');
 END IF;

 UPDATE public.web_rph_bundle_jobs
    SET status='ready',document_manifest_sha256=p_manifest_sha256,
        access_mode=v_result->>'access_mode',
        remaining_after=(v_result->>'remaining')::integer,
        ready_at=now()
  WHERE id=p_job_id AND account_id=p_account_id;
 RETURN v_result || jsonb_build_object('job_id',p_job_id,'status','ready');
END;
$body$;

REVOKE ALL ON FUNCTION public.prepare_web_rph_bundle_staging(uuid,uuid,text)
  FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.prepare_web_rph_bundle_staging(uuid,uuid,text)
  TO service_role;
REVOKE ALL ON FUNCTION public.complete_web_rph_bundle_staging(uuid,uuid,text)
  FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.complete_web_rph_bundle_staging(uuid,uuid,text)
  TO service_role;
COMMIT;
