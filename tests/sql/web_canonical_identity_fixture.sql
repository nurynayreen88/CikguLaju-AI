-- Disposable PostgreSQL test fixture only; matches the production
-- legacy Telegram primary key and trial_remaining contract as audited.
-- The real production table must NEVER be created or modified by this test.
CREATE TABLE public.cikgulaju_users (
    telegram_user_id bigint PRIMARY KEY,
    credits integer NOT NULL DEFAULT 0 CHECK (credits >= 0),
    trial_remaining integer NOT NULL DEFAULT 10
        CHECK (trial_remaining >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Production trial ledger identity/unique-reference contract. Disposable only.
CREATE TABLE public.trial_ledger (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_user_id bigint NOT NULL
        REFERENCES public.cikgulaju_users(telegram_user_id),
    amount integer NOT NULL,
    reason text,
    reference_id text UNIQUE,
    balance_after integer NOT NULL CHECK (balance_after >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Mirror the audited production entitlement and subscription contracts.
-- Fake records are seeded BEFORE any draft canonical migration is applied.
-- This deliberately includes an expired orphan subscription: the migration
-- must preserve historic records rather than deleting or reassociating them.
CREATE TABLE public.pioneer_entitlements (
    telegram_user_id bigint PRIMARY KEY,
    entitlement text NOT NULL DEFAULT 'PIONEER_LIFETIME'
      CHECK (entitlement='PIONEER_LIFETIME'),
    payment_reference text NOT NULL UNIQUE,
    approved_by bigint NOT NULL,
    approved_at timestamptz NOT NULL DEFAULT now(),
    revoked_at timestamptz,
    revoked_by bigint
);
CREATE TABLE public.subscriptions (
    telegram_user_id bigint PRIMARY KEY,
    status text NOT NULL DEFAULT 'inactive',
    plan_code text NOT NULL DEFAULT '30_days',
    started_at timestamptz,
    expires_at timestamptz,
    last_payment_reference text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
