"""Two-provider protected Web routes for one canonical staging account.

No production calls. Google OAuth and Telegram signatures are generated by
the already-tested server-side ticket modules; DB mapping is mocked at the
network boundary for fast authorization and regression checks.
"""
import unittest
from unittest.mock import patch

from flask import Flask
from web.google_web_catalog_staging import bp as catalog_bp
from web.google_rph_bundle_delivery import bp as delivery_bp
from web.google_rph_generation_staging_routes import bp as generation_bp
from web.google_auth_staging_routes import TICKET_COOKIE
from web.google_telegram_signin_staging_routes import (
    TELEGRAM_COOKIE, _issue_ticket,
)
from web_google_identity_sessions import issue_google_identity_ticket


ACCOUNT = "1a267083-8511-4587-a585-857fe35f4a14"
OTHER = "c1351d2d-591d-4ae4-8c92-b0e14d2c3234"
UID = 123456789
SECRET = "canonical-staging-only-test-" + "x" * 40
CFG = {"secret": SECRET, "supabase_url": "https://isolated.supabase.co",
       "staging_service_key": "sb_secret_" + "x"*40,
       "origin": "https://staging.example.org",
       "host": "staging.example.org"}


class LinkedRPHWebTests(unittest.TestCase):
    def setUp(self):
        app = Flask(__name__)
        app.config["TESTING"] = True
        app.register_blueprint(catalog_bp)
        app.register_blueprint(generation_bp)
        app.register_blueprint(delivery_bp)
        self.client = app.test_client()
        self.linked = ACCOUNT
        self.profile_lookups = 0
        self.bundle_lookups = 0

        def profile(cfg, account_id):
            self.assertEqual(cfg, CFG)
            self.assertEqual(account_id, ACCOUNT)
            self.profile_lookups += 1
            return {"display_name": "Guru Ujian", "trial_remaining": 9}

        def linked(cfg, uid):
            self.assertEqual(cfg, CFG)
            self.assertEqual(uid, UID)
            return self.linked

        def ready(cfg, actor, job_id):
            self.assertEqual(cfg, CFG)
            self.assertEqual(actor.account_id, ACCOUNT)
            self.bundle_lookups += 1
            return {"id": job_id, "account_id": ACCOUNT, "status": "ready",
                    "document_manifest_sha256": "a"*64}

        def recent(cfg, actor):
            self.assertEqual(cfg, CFG)
            self.assertEqual(actor.account_id, ACCOUNT)
            return [{"job_id": "1a267083-8511-4587-a585-857fe35f4a14",
                     "downloads": {
                       "word": "/api/google-staging/web/rph/jobs/1a267083-8511-4587-a585-857fe35f4a14/download/word",
                       "pdf": "/api/google-staging/web/rph/jobs/1a267083-8511-4587-a585-857fe35f4a14/download/pdf"}}]

        for p in (
            patch("web.google_web_catalog_staging._enabled_config", return_value=CFG),
            patch("web.google_web_catalog_staging.google_staging_account_profile",
                  new=profile),
            patch("web.google_telegram_link_staging_routes._link_config",
                  return_value=(CFG, ("123456:ABCDEFGHIJKLMNOPQRSTUVWXYZabcdef",
                                      "CikguLajuStagingBot"))),
            patch("web.google_telegram_signin_staging_routes._linked_account",
                  new=linked),
            patch("web.google_rph_bundle_delivery._enabled_config", return_value=CFG),
            patch("web.google_rph_bundle_delivery._ready_job", new=ready),
            patch("web.google_rph_bundle_delivery._recent_ready_jobs", new=recent),
            patch("web.google_rph_bundle_delivery._private_file",
                  return_value=b"%PDF-1.7\\n" + b"x" * 600 + b"\\n%%EOF"),
            patch("web.google_rph_generation_staging_routes._generator_config",
                  return_value=None),
        ):
            p.start()
            self.addCleanup(p.stop)

    def login_telegram(self):
        self.client.set_cookie(TELEGRAM_COOKIE, _issue_ticket(UID, SECRET),
                               domain="localhost")

    def login_google(self, account=ACCOUNT):
        self.client.set_cookie(TICKET_COOKIE, issue_google_identity_ticket(
            account, SECRET), domain="localhost")

    def test_telegram_only_can_select_own_lessons_and_download_existing_rph(self):
        self.login_telegram()
        home = self.client.get("/google-staging-web")
        self.assertEqual(home.status_code, 200, home.data[:200])
        catalog = self.client.get("/api/google-staging/web/catalog")
        self.assertEqual(catalog.status_code, 200, catalog.json)
        self.assertTrue(catalog.json["identity_verified"])
        self.assertEqual(catalog.json["auth_provider"], "telegram")
        self.assertFalse(catalog.json["google_verified"])
        recent = self.client.get("/api/google-staging/web/rph/recent")
        self.assertEqual(recent.status_code, 200, recent.json)
        self.assertEqual(len(recent.json["items"]), 1)
        url = recent.json["items"][0]["downloads"]["pdf"]
        response = self.client.get(url)
        self.assertEqual(response.status_code, 200, response.data[:200])
        self.assertEqual(response.headers["X-RPH-Delivery"],
                         "private-staging-bundle")
        self.assertEqual(self.bundle_lookups, 1)

        caps = self.client.get("/api/google-staging/web/rph/capabilities")
        self.assertEqual(caps.status_code, 200)
        self.assertFalse(caps.json["generation_enabled"])
        self.assertFalse(caps.json["google_verified"])
        self.assertTrue(caps.json["identity_verified"])
        self.assertEqual(caps.json["auth_provider"], "telegram")
        denied = self.client.post(
            "/api/google-staging/web/rph/issue",
            json={"selection": {}},
            headers={"Origin": CFG["origin"], "Sec-Fetch-Site": "same-origin"})
        self.assertEqual(denied.status_code, 503)
        self.assertEqual(self.profile_lookups >= 3, True)

    def test_google_only_reads_same_account(self):
        self.login_google()
        result = self.client.get("/api/google-staging/web/catalog")
        self.assertEqual(result.status_code, 200, result.json)
        self.assertTrue(result.json["google_verified"])
        self.assertEqual(result.json["auth_provider"], "google")

    def test_conflicting_valid_cookies_denied_for_catalog_and_download(self):
        self.login_telegram()
        self.login_google(OTHER)
        self.assertEqual(self.client.get(
            "/api/google-staging/web/catalog").status_code, 403)
        self.assertEqual(self.client.get(
            "/api/google-staging/web/rph/recent").status_code, 403)
        self.assertEqual(self.bundle_lookups, 0)

    def test_same_account_dual_cookie_is_accepted_without_second_account(self):
        self.login_telegram()
        self.login_google()
        res = self.client.get("/api/google-staging/web/catalog")
        self.assertEqual(res.status_code, 200)
        self.assertEqual(res.json["auth_provider"], "google")

    def test_removed_link_fails_closed_even_with_signed_telegram_cookie(self):
        self.login_telegram()
        self.linked = None
        self.assertEqual(self.client.get(
            "/api/google-staging/web/catalog").status_code, 401)
        self.assertEqual(self.client.get(
            "/api/google-staging/web/rph/recent").status_code, 401)
        self.assertEqual(self.bundle_lookups, 0)

    def test_anonymous_is_denied(self):
        self.assertEqual(self.client.get(
            "/api/google-staging/web/catalog").status_code, 401)
        self.assertEqual(self.client.get(
            "/api/google-staging/web/rph/recent").status_code, 401)


if __name__ == "__main__":
    unittest.main()
